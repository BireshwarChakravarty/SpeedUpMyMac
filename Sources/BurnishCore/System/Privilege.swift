/// Builds a root shell script out of fixed commands and shell-quoted arguments only.
/// This is the only way anything in Burnish reaches root.
public struct PrivilegedScript: Sendable, Equatable {
    public private(set) var lines: [String] = []

    public init() {}

    public var isEmpty: Bool { lines.isEmpty }

    /// Appends a command; every argument is quoted.
    public mutating func add(_ executable: String, _ arguments: [String] = [], tolerateFailure: Bool = true) {
        let cmd = ([executable] + arguments).map(Shell.quote).joined(separator: " ")
        lines.append(tolerateFailure ? "\(cmd) || true" : cmd)
    }

    /// Appends a removal; the path must already have passed `Safety.validateForDeletion`.
    public mutating func remove(_ path: String) {
        add("/bin/rm", ["-rf", "--", path])
    }

    /// Appends a fixed, pre-written snippet. Only use with literals from Burnish's own catalog.
    public mutating func addTrusted(_ snippet: String) {
        lines.append(snippet)
    }

    public var text: String {
        (["#!/bin/sh", "# Generated by Burnish — runs as root"] + lines).joined(separator: "\n") + "\n"
    }
}

public enum PrivilegeError: Error, LocalizedError {
    case notAdmin
    case cancelled
    case failed(String)

    public var errorDescription: String? {
        switch self {
        case .notAdmin: return "This account is not an administrator. System-level actions are unavailable on this Mac."
        case .cancelled: return "Authorization was cancelled."
        case .failed(let message): return message
        }
    }
}

/// Something that can run a `PrivilegedScript` as root.
public protocol PrivilegeRunner: Sendable {
    func run(_ script: PrivilegedScript, reason: String) throws -> ShellResult
}

public enum Privilege {
    /// `true` when the current user is in the `admin` group (can use sudo / authorize as admin).
    public static func currentUserIsAdmin() -> Bool {
        if let forced = ProcessInfo.processInfo.environment["BURNISH_FORCE_ADMIN"] { return forced == "1" }
        let r = Shell.run("/usr/bin/id", ["-Gn"])
        guard r.succeeded else { return false }
        let groups = r.stdout.split(whereSeparator: { $0 == " " || $0 == "\n" }).map(String.init)
        return groups.contains("admin")
    }

    public static var isRoot: Bool { getuid() == 0 }

    /// The runner for GUI contexts: one macOS authorization dialog (password or Touch ID) per script.
    public static func appleScriptRunner() -> PrivilegeRunner { AppleScriptRunner() }

    /// The runner for terminal contexts: `sudo` with the terminal attached.
    public static func sudoRunner() -> PrivilegeRunner { SudoRunner() }
}

/// Runs the script with `do shell script … with administrator privileges`. The script is passed
/// to osascript as an argv item (not interpolated into AppleScript source, not written to disk),
/// so there is no quoting bug to exploit and nothing on disk to swap before root executes it.
struct AppleScriptRunner: PrivilegeRunner {
    func run(_ script: PrivilegedScript, reason: String) throws -> ShellResult {
        guard Privilege.currentUserIsAdmin() else { throw PrivilegeError.notAdmin }
        guard !script.isEmpty else { return ShellResult(status: 0, stdout: "", stderr: "") }
        let source = [
            "on run argv",
            "  do shell script (item 1 of argv) with prompt (item 2 of argv) with administrator privileges",
            "end run",
        ]
        var args: [String] = []
        for line in source { args += ["-e", line] }
        args += [script.text, "Burnish: \(reason)"]
        let result = Shell.run("/usr/bin/osascript", args, timeout: 1800)
        if !result.succeeded && result.stderr.contains("-128") { throw PrivilegeError.cancelled }
        return result
    }
}

/// Runs the script through `sudo /bin/sh -c`. Prompts on the attached terminal if needed
/// (Touch ID works when pam_tid is enabled in /etc/pam.d/sudo_local).
struct SudoRunner: PrivilegeRunner {
    func run(_ script: PrivilegedScript, reason: String) throws -> ShellResult {
        guard Privilege.currentUserIsAdmin() || Privilege.isRoot else { throw PrivilegeError.notAdmin }
        guard !script.isEmpty else { return ShellResult(status: 0, stdout: "", stderr: "") }
        if Privilege.isRoot { return Shell.run("/bin/sh", ["-c", script.text], timeout: 1800) }
        // Validate (and possibly prompt) with the terminal attached, then run non-interactively.
        if Shell.run("/usr/bin/sudo", ["-n", "true"]).status != 0 {
            FileHandle.standardError.write(Data("burnish: admin access needed for \(reason)\n".utf8))
            guard Shell.runInteractive("/usr/bin/sudo", ["-v"]) == 0 else { throw PrivilegeError.cancelled }
        }
        return Shell.run("/usr/bin/sudo", ["-n", "/bin/sh", "-c", script.text], timeout: 1800)
    }
}

/// Records the script instead of running it (dry runs and tests).
public final class RecordingRunner: PrivilegeRunner, @unchecked Sendable {
    public private(set) var scripts: [PrivilegedScript] = []
    public init() {}
    public func run(_ script: PrivilegedScript, reason: String) throws -> ShellResult {
        scripts.append(script)
        return ShellResult(status: 0, stdout: "", stderr: "")
    }
}

/// Runs a prefix (e.g. `launchctl bootout` for daemons) in the same authorization as the main script.
public struct PrependingRunner: PrivilegeRunner {
    public var prefix: PrivilegedScript
    public var base: PrivilegeRunner

    public init(prefix: PrivilegedScript, base: PrivilegeRunner) {
        self.prefix = prefix
        self.base = base
    }

    public func run(_ script: PrivilegedScript, reason: String) throws -> ShellResult {
        var combined = prefix
        for line in script.lines { combined.addTrusted(line) }
        return try base.run(combined, reason: reason)
    }
}
